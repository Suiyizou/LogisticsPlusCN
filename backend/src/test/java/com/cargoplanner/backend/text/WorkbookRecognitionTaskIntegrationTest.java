  private String toolCompletion(String id, String name, Map<String, Object> arguments) throws Exception {
    return mapper.writeValueAsString(Map.of("choices", List.of(Map.of("finish_reason", "tool_calls", "message", Map.of(
        "role", "assistant", "content", "", "tool_calls", List.of(Map.of("id", id, "type", "function", "function",
            Map.of("name", name, "arguments", mapper.writeValueAsString(arguments)))))))));
  }

  private String completion(String content) throws Exception {
    return mapper.writeValueAsString(Map.of("choices", List.of(Map.of("finish_reason", "stop", "message", Map.of("role", "assistant", "content", content)))));
  }

  @SuppressWarnings("unchecked")
  private Map<String, Object> inner(Map<String, Object> cargo) {
    return (Map<String, Object>) ((Map<String, Object>) cargo.get("packageInfo")).get("innerCargo");
  }

  private double number(Object value) {
    return ((Number) value).doubleValue();
  }
