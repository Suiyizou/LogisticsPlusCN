    assertEquals(2, ((List<Map<String, Object>>) task.get("cleanedRows")).get(0).get("quantity"));
    assertFalse(mapper.writeValueAsString(task).contains("base64"));
    assertEquals("IMAGE", service.listTasks().get(0).get("taskType"));
