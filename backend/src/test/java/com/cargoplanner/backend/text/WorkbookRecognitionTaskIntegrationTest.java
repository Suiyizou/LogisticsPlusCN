  @Test
  @SuppressWarnings("unchecked")
  void auditedSourcePrecisionSurvivesNormalizationPersistenceAndExport() throws Exception {
    Map<String, Object> document;
    try (Workbook source = new XSSFWorkbook(); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
      var sheet = source.createSheet("Packages");
      List<String> headers = List.of("Package No", "Marks", "Product", "Model", "Inner Qty", "Unit Net", "Net", "Gross", "Dimensions");
      var header = sheet.createRow(0);
      for (int col = 0; col < headers.size(); col++) header.createCell(col).setCellValue(headers.get(col));
      var row = sheet.createRow(1);
      row.createCell(0).setCellValue(123); row.createCell(1).setCellValue(7);
      row.createCell(2).setCellValue("Small parts"); row.createCell(3).setCellValue(42);
      row.createCell(4).setCellValue(3); row.createCell(5).setCellValue(0.025);
      row.createCell(7).setCellValue(0.125); row.createCell(8).setCellValue("33.333*20.125*10.005");
      var numberFormat = source.createDataFormat();
      for (var formatted : Map.of(0, "000000", 1, "\"BOX\"0000", 3, "00000", 7, "0.0").entrySet()) {
        var style = source.createCellStyle();
        style.setDataFormat(numberFormat.getFormat(formatted.getValue()));
        row.getCell(formatted.getKey()).setCellStyle(style);
      }
      source.write(output);
      document = new WorkbookEvidenceService().parse(output.toByteArray(), "precision.xlsx");
    }
    Map<String, Object> mapping = plan();
    mapping.put("firstDataRow", 2); mapping.put("lastDataRow", 2); mapping.put("dimensionUnit", "cm");
    Map<String, Object> totals = new LinkedHashMap<>();
    for (String metric : List.of("packageCount", "innerQuantity", "grossWeight", "netWeight", "volume")) totals.put(metric + "Cell", null);
    mapping.put("totals", totals);
    model.expect(once(), anything()).andRespond(withSuccess(toolCompletion("read-precision", "read_sheet_range",
        Map.of("sheet", "Packages", "range", "A1:I2")), MediaType.APPLICATION_JSON));
    model.expect(once(), anything()).andRespond(withSuccess(completion(mapper.writeValueAsString(Map.of("plans", List.of(mapping)))), MediaType.APPLICATION_JSON));
    long id = ((Number) service.createWorkbookTask(document, "precision.xlsx", "en").get("id")).longValue();
    Map<String, Object> task = awaitTask(id);
    assertEquals("SUCCEEDED", task.get("status"), String.valueOf(task.get("errorMessage")));
    assertFalse(Boolean.TRUE.equals(task.get("partial")));
    Map<String, Object> cargo = ((List<Map<String, Object>>) task.get("cleanedRows")).get(0);
    assertEquals("000123", cargo.get("packageNo"));
    assertEquals("BOX0007", cargo.get("marks"));
    assertEquals("00042", cargo.get("model"));
    assertEquals(0.125, cargo.get("weightKg"));
    assertEquals(33.333, cargo.get("lengthCm"));
    assertEquals(20.125, cargo.get("widthCm"));
    assertEquals(10.005, cargo.get("heightCm"));
    Map<String, Object> actual = (Map<String, Object>) ((Map<String, Object>) task.get("reconciliation")).get("actual");
    assertEquals(number(cargo.get("weightKg")), number(actual.get("grossWeightKg")));
    try (Workbook exported = WorkbookFactory.create(new ByteArrayInputStream(service.cleanedWorkbook(id)))) {
      assertEquals(0.125, exported.getSheetAt(0).getRow(1).getCell(6).getNumericCellValue());
      assertEquals(0.125, exported.getSheetAt(0).getRow(1).getCell(18).getNumericCellValue());
      assertEquals(33.333, exported.getSheetAt(0).getRow(1).getCell(2).getNumericCellValue());
      assertEquals("000123", exported.getSheetAt(0).getRow(1).getCell(13).getStringCellValue());
      assertEquals("BOX0007", exported.getSheetAt(0).getRow(1).getCell(14).getStringCellValue());
    }
    model.verify();
  }

  private Map<String, Object> awaitTask(long id) throws InterruptedException {
    long deadline = System.nanoTime() + Duration.ofSeconds(20).toNanos();
    Map<String, Object> task;
    do {
      task = service.getTask(id);
      if (List.of("SUCCEEDED", "FAILED").contains(String.valueOf(task.get("status")))) return task;
      Thread.sleep(20);
    } while (System.nanoTime() < deadline);
    throw new AssertionError("Recognition task did not complete: " + task);
  }

