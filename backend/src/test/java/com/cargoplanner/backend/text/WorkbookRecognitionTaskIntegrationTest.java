  @Test
  @SuppressWarnings("unchecked")
  void nativeWorkbookToolsReadAllPackagesAndContentsThroughThePersistedTaskAndExcelExport() throws Exception {
    Map<String, Object> document = fixtureDocument();
    model.expect(once(), anything()).andRespond(withSuccess(toolCompletion("inspect-1", "inspect_workbook", Map.of()), MediaType.APPLICATION_JSON));
    model.expect(once(), anything()).andRespond(withSuccess(toolCompletion("read-1", "read_sheet_range",
        Map.of("sheet", "Packages", "range", "A1:J114")), MediaType.APPLICATION_JSON));
    model.expect(once(), anything()).andRespond(withSuccess(completion(mapper.writeValueAsString(Map.of("plans", List.of(plan())))), MediaType.APPLICATION_JSON));

    Map<String, Object> started = service.createWorkbookTask(document, "mixed-packages.xlsx", "en");
    long id = ((Number) started.get("id")).longValue();
    Map<String, Object> task = awaitTask(id);
    assertEquals("SUCCEEDED", task.get("status"), String.valueOf(task.get("errorMessage")));
    assertFalse(Boolean.TRUE.equals(task.get("partial")));
    List<Map<String, Object>> rows = (List<Map<String, Object>>) task.get("cleanedRows");
    assertEquals(75, rows.size());
    assertEquals(75, rows.stream().mapToInt(row -> ((Number) row.get("quantity")).intValue()).sum());
    assertEquals(74575.0, rows.stream().mapToDouble(row -> ((Number) row.get("quantity")).doubleValue()
        * ((Number) row.get("weightKg")).doubleValue()).sum(), 0.001);
    assertEquals(6925, rows.stream().mapToInt(row -> ((Number) inner(row).get("totalQuantity")).intValue()).sum());
    assertEquals(93.528148, rows.stream().mapToDouble(row -> number(row.get("lengthCm")) * number(row.get("widthCm"))
        * number(row.get("heightCm")) / 1_000_000 * number(row.get("quantity"))).sum(), 0.000001);
    assertEquals(75, rows.stream().map(row -> row.get("marks")).distinct().count());
    assertEquals(22, ((Number) inner(rows.get(0)).get("totalQuantity")).intValue());
    assertEquals(2, ((List<?>) inner(rows.get(0)).get("lines")).size());
    Map<String, Object> reconciliation = (Map<String, Object>) task.get("reconciliation");
    assertNotNull(reconciliation);
    assertEquals("review-required", reconciliation.get("status"));
    assertFalse(((List<?>) reconciliation.get("warnings")).isEmpty());
    assertEquals(id, ((Number) reconciliation.get("sourceTaskId")).longValue());
    assertEquals(false, reconciliation.get("partial"));
    for (Map<String, Object> row : rows) {
      Map<String, Object> sourceAudit = (Map<String, Object>) ((Map<String, Object>) row.get("packageInfo")).get("sourceReconciliation");
      assertEquals(reconciliation, sourceAudit);
    }
    assertTrue(jdbc.queryForObject("SELECT raw_text FROM cp_text_recognition_tasks WHERE id=?", String.class, id)
        .startsWith("WORKBOOK_TOOL_DOCUMENT_V1\n"));
    assertFalse(jdbc.queryForObject("SELECT raw_text FROM cp_text_recognition_tasks WHERE id=?", String.class, id)
        .contains("EXCEL_AGENT_BATCH"));
    try (Workbook exported = WorkbookFactory.create(new ByteArrayInputStream(service.cleanedWorkbook(id)))) {
      assertEquals(75, exported.getSheetAt(0).getLastRowNum());
      assertNotNull(exported.getSheet("reconciliation"));
      assertEquals("marks", exported.getSheetAt(0).getRow(0).getCell(14).getStringCellValue());
      assertEquals("PACK#1", exported.getSheetAt(0).getRow(1).getCell(14).getStringCellValue());
      Map<String, Object> exportedInfo = mapper.readValue(exported.getSheetAt(0).getRow(1).getCell(20).getStringCellValue(), Map.class);
      assertEquals(reconciliation, exportedInfo.get("sourceReconciliation"));
    }
    model.verify();
  }

  @Test
  @SuppressWarnings("unchecked")
  void globalSourceFailureRemainsAttachedToEveryExportedRowWithoutCargoRecursion() throws Exception {
    Map<String, Object> document = fixtureDocument();
    List<Map<String, Object>> sheets = (List<Map<String, Object>>) document.get("sheets");
    for (Map<String, Object> cell : (List<Map<String, Object>>) sheets.get(0).get("cells")) {
      if ("H113".equals(cell.get("address"))) {
        cell.put("value", 75575); cell.put("displayValue", "75575");
      }
    }
    model.expect(once(), anything()).andRespond(withSuccess(toolCompletion("read-blocked", "read_sheet_range",
        Map.of("sheet", "Packages", "range", "A1:J114")), MediaType.APPLICATION_JSON));
    model.expect(once(), anything()).andRespond(withSuccess(completion(mapper.writeValueAsString(Map.of("plans", List.of(plan())))), MediaType.APPLICATION_JSON));
    long id = ((Number) service.createWorkbookTask(document, "wrong-total.xlsx", "en").get("id")).longValue();
    Map<String, Object> task = awaitTask(id);
    assertEquals("SUCCEEDED", task.get("status"));
    assertEquals(true, task.get("partial"));
    Map<String, Object> report = (Map<String, Object>) task.get("reconciliation");
    assertEquals("blocked", report.get("status"));
    assertEquals(true, report.get("partial"));
    assertEquals(id, ((Number) report.get("sourceTaskId")).longValue());
    assertFalse(report.containsKey("cleanedRows"));
    assertEquals(75575.0, ((Map<String, Object>) report.get("expected")).get("grossWeightKg"));
    assertEquals(74575.0, ((Map<String, Object>) report.get("actual")).get("grossWeightKg"));
    List<Map<String, Object>> rows = (List<Map<String, Object>>) task.get("cleanedRows");
    assertEquals(75, rows.size());
    for (Map<String, Object> cargo : rows) {
      Map<String, Object> info = (Map<String, Object>) cargo.get("packageInfo");
      assertFalse(info.containsKey("sourceIssues"), "Failure is global, not a fabricated per-row error");
      assertEquals(report, info.get("sourceReconciliation"));
    }
    try (Workbook exported = WorkbookFactory.create(new ByteArrayInputStream(service.cleanedWorkbook(id)))) {
      for (int row = 1; row <= 75; row++) {
        Map<String, Object> info = mapper.readValue(exported.getSheetAt(0).getRow(row).getCell(20).getStringCellValue(), Map.class);
        assertEquals(report, info.get("sourceReconciliation"));
      }
      assertNotNull(exported.getSheet("reconciliation"));
    }
    model.verify();
  }

