  @SuppressWarnings("unchecked")
  private Map<String, Object> fixtureDocument() throws Exception {
    Map<String, Object> fixture;
    try (var input = getClass().getResourceAsStream("/packing-lists/mixed-package-source.json")) {
      assertNotNull(input);
      fixture = mapper.readValue(input, new TypeReference<Map<String, Object>>() {});
    }
    Map<String, Object> sourceSheet = (Map<String, Object>) fixture.get("sheet");
    try (Workbook workbook = new XSSFWorkbook(); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
      var sheet = workbook.createSheet("Packages");
      List<List<Object>> rawRows = (List<List<Object>>) sourceSheet.get("rawRows");
      for (int row = 0; row < rawRows.size(); row++) {
        var excelRow = sheet.createRow(row);
        for (int col = 0; col < rawRows.get(row).size(); col++) excelRow.createCell(col).setCellValue(String.valueOf(rawRows.get(row).get(col)));
      }
      for (Object range : (List<?>) sourceSheet.get("merges")) sheet.addMergedRegion(CellRangeAddress.valueOf(String.valueOf(range)));
      workbook.write(output);
      return new WorkbookEvidenceService().parse(output.toByteArray(), "mixed-packages.xlsx");
    }
  }

