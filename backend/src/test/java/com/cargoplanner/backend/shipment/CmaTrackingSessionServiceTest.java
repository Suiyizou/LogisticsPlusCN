package com.cargoplanner.backend.shipment;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.cargoplanner.backend.auth.AuthenticatedUser;
import com.cargoplanner.backend.common.ApiException;
import com.cargoplanner.backend.shipment.CmaTrackingSessionService.CmaSessionUpdateRequest;
import java.nio.file.Path;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class CmaTrackingSessionServiceTest {
  @TempDir
  Path temporaryDirectory;

  private JdbcTemplate jdbcTemplate;
  private CmaTrackingSessionService service;
  private AuthenticatedUser business;

  @BeforeEach
  void setUp() {
    DriverManagerDataSource dataSource = new DriverManagerDataSource(
        "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1",
        "sa",
        ""
    );
    jdbcTemplate = new JdbcTemplate(dataSource);
    jdbcTemplate.execute("""
        CREATE TABLE cp_users (
          id BIGINT PRIMARY KEY,
          display_name VARCHAR(80) NOT NULL,
          role VARCHAR(20) NOT NULL
        )
        """);
    jdbcTemplate.execute("""
        CREATE TABLE cp_tracking_credentials (
          carrier_code VARCHAR(32) PRIMARY KEY,
          encrypted_session_cookie CLOB NOT NULL,
          browser_user_agent VARCHAR(512),
          updated_by BIGINT,
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """);
    jdbcTemplate.execute("""
        CREATE TABLE cp_admin_audit_log (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          admin_user_id BIGINT,
          action VARCHAR(80) NOT NULL,
          target_type VARCHAR(40),
          target_id BIGINT,
          detail VARCHAR(512),
          ip_address VARCHAR(64),
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """);
    jdbcTemplate.update("INSERT INTO cp_users (id, display_name, role) VALUES (7, 'Business Seven', 'BUSINESS')");
    jdbcTemplate.update("INSERT INTO cp_users (id, display_name, role) VALUES (8, 'Employee Eight', 'EMPLOYEE')");
    business = new AuthenticatedUser(7, "business7", "Business Seven", "BUSINESS", "ACTIVE");
    service = new CmaTrackingSessionService(
        jdbcTemplate,
        new SecretValueCodec(temporaryDirectory.resolve("tracking.key"))
    );
  }

  @Test
  void encryptsAndNeverReturnsTheStoredCookieFromStatus() {
    String cookie = "datadome=secret-session==; XSRF-TOKEN=secondary";
    var status = service.update(
        new CmaSessionUpdateRequest(cookie, "Mozilla/5.0 Test Browser"),
        business,
        "127.0.0.1"
    );

    assertThat(status.configured()).isTrue();
    assertThat(status.cookieName()).isEqualTo("datadome");
    assertThat(status.updatedBy()).isEqualTo("Business Seven");
    assertThat(status.toString()).doesNotContain("secret-session");

    String stored = jdbcTemplate.queryForObject(
        "SELECT encrypted_session_cookie FROM cp_tracking_credentials WHERE carrier_code = 'CMA'",
        String.class
    );
    assertThat(stored).startsWith("v1:").doesNotContain("secret-session");
    assertThat(service.requireCredentials().sessionCookie()).isEqualTo(cookie);
    assertThat(service.requireCredentials().userAgent()).isEqualTo("Mozilla/5.0 Test Browser");
    assertThat(jdbcTemplate.queryForObject(
        "SELECT action FROM cp_admin_audit_log",
        String.class
    )).isEqualTo("UPDATE_CMA_TRACKING_SESSION");
  }

  @Test
  void restrictsMaintenanceToBusinessUsersAndAdministrators() {
    AuthenticatedUser employee = new AuthenticatedUser(
        8,
        "employee8",
        "Employee Eight",
        "EMPLOYEE",
        "ACTIVE"
    );

    assertThatThrownBy(() -> service.update(
        new CmaSessionUpdateRequest("datadome=secret", "Mozilla/5.0"),
        employee,
        "127.0.0.1"
    )).isInstanceOf(ApiException.class)
        .satisfies(error -> assertThat(((ApiException) error).status()).isEqualTo(HttpStatus.FORBIDDEN));
  }

  @Test
  void clearsTheCredentialAndItsUsability() {
    service.update(
        new CmaSessionUpdateRequest("only-the-datadome-value", "Mozilla/5.0"),
        business,
        "127.0.0.1"
    );

    assertThat(service.requireCredentials().sessionCookie())
        .isEqualTo("datadome=only-the-datadome-value");
    assertThat(service.clear(business, "127.0.0.1").configured()).isFalse();
    assertThat(service.credentials()).isEmpty();
    assertThat(jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM cp_admin_audit_log WHERE action = 'CLEAR_CMA_TRACKING_SESSION'",
        Integer.class
    )).isEqualTo(1);
  }

  @Test
  void reusesThePersistentKeyAndBindsCiphertextToItsPurpose() {
    Path keyFile = temporaryDirectory.resolve("persistent.key");
    SecretValueCodec first = new SecretValueCodec(keyFile);
    String encrypted = first.encrypt("purpose-a", "sensitive-value");

    SecretValueCodec restarted = new SecretValueCodec(keyFile);
    assertThat(restarted.decrypt("purpose-a", encrypted)).isEqualTo("sensitive-value");
    assertThatThrownBy(() -> restarted.decrypt("purpose-b", encrypted))
        .isInstanceOf(IllegalStateException.class);
  }
}
