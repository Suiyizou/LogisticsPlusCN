export function navigatorFailure(code, message) {
  const error = new Error(message);
  error.name = 'HapagNavigatorError';
  error.code = code;
  return error;
}

export function navigatorQuery(job) {
  if (job?.carrier !== 'HAPAG_LLOYD' || !TYPES.has(job.reference_type))
    throw navigatorFailure('UNSUPPORTED_REFERENCE_TYPE','Navigator requires an explicit Hapag container, booking or bill-of-lading query');
  const submitted = String(job.submitted ?? job.reference ?? '').replace(/\s+/g,'').toUpperCase();
  if (!submitted || String(job.reference ?? '').replace(/\s+/g,'').toUpperCase()!==submitted || !/^[A-Z0-9]{4,40}$/.test(submitted) ||
      (job.reference_type === 'CONTAINER' && !/^[A-Z]{4}\d{7}$/.test(submitted)))
    throw navigatorFailure('INVALID_REFERENCE','Navigator reference is not a supported visible search value');
  return {...job,submitted};
}

function poolSnapshot(record) {
  return {ownership:'WORKER_CREATED_HAPAG_NAVIGATOR_PAGE',
    state:!record ? 'EMPTY' : record.quarantined ? 'QUARANTINED' : record.busy ? 'BUSY' : 'READY',
    page_retained:Boolean(record?.page),reason:record?.reason ?? null};
}

export function inspectNavigatorPagePool(context) {
  return poolSnapshot(context && (typeof context === 'object' || typeof context === 'function') ? pools.get(context) : null);
}

export async function acquireNavigatorPage(context) {
  if (!context || !['object','function'].includes(typeof context) || typeof context.newPage !== 'function')
    throw navigatorFailure('NAVIGATOR_CONTEXT_REQUIRED','Navigator needs an explicit connected browser context');
  let record = pools.get(context);
  if (record?.busy) throw navigatorFailure('NAVIGATOR_PAGE_BUSY','This worker Navigator page is already in use');
  if (record?.quarantined) throw navigatorFailure('NAVIGATOR_PAGE_QUARANTINED','This worker Navigator page is retained after an unsuccessful query; no replacement was opened');
  if (record?.page?.isClosed?.()) {
    record.quarantined = true;
    record.reason = 'OWNED_PAGE_CLOSED';
    throw navigatorFailure('NAVIGATOR_PAGE_QUARANTINED','This worker Navigator page closed; no other page was adopted');
  }
  if (!record) {
    record = {page:null,busy:true,quarantined:false,reason:null,lease:null,ownedPageId:randomUUID()};
    pools.set(context,record);
    try {
      record.page = await context.newPage();
      if (!record.page || typeof record.page !== 'object') throw Error('Page unavailable');
    } catch {
      record.busy = false;
      record.quarantined = true;
      record.reason = 'OWNED_PAGE_CREATION_FAILED';
      throw navigatorFailure('NAVIGATOR_PAGE_CREATION_FAILED','The worker could not create its own Navigator page; no existing page was adopted');
    }
  }
  record.busy = true;
  const token = Symbol('navigator-lease');
  record.lease = token;
  let released = false;
  return {page:record.page,ownedPageId:record.ownedPageId,release({status = 'FAILED',reason = status} = {}) {
    if (released || record.lease !== token) return poolSnapshot(record);
    released = true;
    record.lease = null;
    record.busy = false;
    if (status === 'QUERY_COMPLETED' || status === 'ACCOUNT_SCOPE_NO_RESULTS') record.reason = null;
    else {
      record.quarantined = true;
      record.reason = String(reason).slice(0,100);
    }
    return poolSnapshot(record);
  }};
}

export function navigatorActionId() { return randomUUID(); }

export function navigatorPublicUrl(value) {
  const location=hapagSafePublicLocation(value);
  return location.origin&&/^https?:\/\//.test(location.origin)?location.origin+location.path:null;
}

// Observe metadata of requests generated by ordinary page actions only. No
// response bodies, headers, query strings, cookies or application state are read.
export function observeNavigatorUiRequests(page, actionId) {
  const requests = new WeakMap(), metadata = [];
  const requested = request => {
    if (metadata.length >= 200) return;
    const item = {actionId,method:request.method(),resourceType:request.resourceType(),url:navigatorPublicUrl(request.url()),status:null};
    requests.set(request,item); metadata.push(item);
  };
  const responded = response => {
    const item = requests.get(response.request());
    if (item) item.status = response.status();
  };
  page.on('request',requested); page.on('response',responded);
  return {metadata,markSearchStart:()=>metadata.length,stop() {page.off('request',requested);page.off('response',responded);}};
}

export function confirmedNavigatorUiResponse(metadata,query) {
  const type={BOOKING:'SHIPMENT',BILLOFLADING:'MTD',CONTAINER:'CONTAINER'}[query.reference_type];
  const expected=`https://navigator.api.hlag.cloud/api/shipments/${type}/${query.submitted}`;
  const matching=metadata.filter(item=>item.method==='GET'&&item.url===expected);
  if(matching.some(item=>[401,403].includes(item.status)))
    throw navigatorFailure('LOGIN_REQUIRED','The ordinary account UI reported an authentication or permission error; no alternate scope was requested');
  if(matching.some(item=>item.status===429))
    throw navigatorFailure('NAVIGATOR_ACCOUNT_UI_RATE_LIMITED','The ordinary account UI was rate limited; the controller did not retry');
  const result=matching.find(item=>item.status===200);
  return result?{confirmed:true,kind:'NORMAL_UI_RESPONSE_METADATA',method:'GET',url:expected,status:200,requestStartedAfterClear:true}:null;
}

function navigatorBudget(end,max = 7000) {
  const remaining = end - Date.now();
  if (remaining < 100) throw navigatorFailure('NAVIGATOR_BUDGET_EXHAUSTED','Navigator ordinary UI query reached its fixed time budget');
  return Math.max(1,Math.min(max,remaining - 50));
}

export async function assertNavigatorAvailable(page,end) {
  const websiteGate = hapagWebsiteLoginGuard(page);
  if (websiteGate) return websiteGate.assertAvailable();
  // Automatic browser checking can be a transient loading screen. Observe this
  // same page for at most 30 seconds within the unchanged whole-query budget;
  // never reload, navigate, create another context or interact with a widget.
  const pendingDeadline = Math.min(end - 100,Date.now() + 30000);
  let pendingSeen = false;
  for (;;) {
    if (pendingSeen && Date.now() >= pendingDeadline)
      throw navigatorFailure('HUMAN_CAPTCHA','The passive official browser check did not complete within its existing budget; no verification action was made');
    navigatorBudget(end);
    let verification;
    try { verification = await checkHapagVerification(page); }
    catch (error) {
      if (error.code === 'HUMAN_CAPTCHA') throw navigatorFailure('HUMAN_CAPTCHA','The official page requires verification; Navigator made no verification action');
      throw error;
    }
    const text = await page.locator('body').innerText({timeout:navigatorBudget(end,3000)}).catch(()=> '');
    if (/请验证您是真人/u.test(text.replace(/\s+/gu,'')) || /verify (?:that )?you are human|please complete the captcha/i.test(text))
      throw navigatorFailure('HUMAN_CAPTCHA','The official page requires verification; Navigator made no verification action');
    if (await page.locator('input[type="password"]:visible').count())
      throw navigatorFailure('LOGIN_REQUIRED','Navigator needs an already available normal account login; no credentials were submitted');
    if (!verification.pending) return;
    pendingSeen = true;
    const remaining = pendingDeadline - Date.now();
    if (remaining <= 0)
      throw navigatorFailure('HUMAN_CAPTCHA','The passive official browser check did not complete within its existing budget; no verification action was made');
    await page.waitForTimeout(Math.min(200,remaining));
  }
}

// Public rendered search UI only. The main shipment table's similarly numbered
// links are deliberately excluded from candidates.
export function readNavigatorSearchState() {
  const clean = value => String(value ?? '').replace(/\s+/g,' ').trim();
  const visible = element => !!element?.getClientRects().length && getComputedStyle(element).visibility !== 'hidden';
  const regions = [...document.querySelectorAll('.search-bar__results .hl-gutter-16')].filter(visible).map(root=>{
    const headings = [...root.children].filter(visible).map(element=>clean(element.innerText))
      .filter(text=>/^\d+ Results? for\b|^No results for\b/i.test(text));
    const numbers = [...root.querySelectorAll('span.shipment-element__shipment-number')].filter(visible).map(element=>clean(element.innerText));
    return {headings,numbers};
  }).filter(region=>region.headings.length);
  return {regions,candidateCount:[...document.querySelectorAll('.search-bar__results span.shipment-element__shipment-number')].filter(visible).length};
}

export function matchNavigatorSearchState(state,submitted) {
  const key = value => String(value ?? '').replace(/\s+/g,'').toUpperCase();
  const matches = [];
  for (const region of state?.regions ?? []) for (const heading of region.headings ?? []) {
    const empty = /^No results for\s+(.+)$/i.exec(heading);
    if (empty && key(empty[1]) === key(submitted)) {
      if ((region.numbers ?? []).length || state.candidateCount !== 0)
        throw navigatorFailure('NAVIGATOR_AMBIGUOUS_SEARCH_RESULT','A no-results message coexists with a visible candidate; no result was accepted');
      matches.push({status:'ACCOUNT_SCOPE_NO_RESULTS',numbers:[]});
    }
    const found = /^(\d+) Results? for\s+(.+)$/i.exec(heading);
    if (found && key(found[2]) === key(submitted)) {
      const count = Number(found[1]), numbers = (region.numbers ?? []).map(key);
      if (count !== 1 || numbers.length !== 1 || state.candidateCount !== 1)
        throw navigatorFailure('NAVIGATOR_AMBIGUOUS_SEARCH_RESULT','The fresh account search did not expose one unique shipment candidate');
      matches.push({status:'SELECTABLE',numbers});
    }
  }
  if (matches.length > 1) throw navigatorFailure('NAVIGATOR_AMBIGUOUS_SEARCH_RESULT','More than one visible search result region binds the requested reference');
  return matches[0] ?? null;
}

async function waitNavigatorState(page,end,predicate,{max = 60000,reason = 'NAVIGATOR_UI_NOT_READY'} = {}) {
  const until = Math.min(end,Date.now()+max);
  while (Date.now() < until) {
    await assertNavigatorAvailable(page,end);
    const value = await predicate();
    if (value) return value;
    await page.waitForTimeout(Math.min(200,navigatorBudget(end,200)));
  }
  await assertNavigatorAvailable(page,end);
  throw navigatorFailure(reason,'The expected ordinary Navigator UI state was not confirmed within the existing query budget');
}

