export async function clickExactlyOne(locator,end,code = 'NAVIGATOR_CONTROL_AMBIGUOUS') {
  if (await locator.count() > 1)
    throw navigatorFailure(code,'More than one ordinary Navigator control matched; no alternative control was clicked');
  try { await locator.waitFor({state:'visible',timeout:navigatorBudget(end)}); }
  catch (error) {
    if (error.code === 'NAVIGATOR_BUDGET_EXHAUSTED') throw error;
    if (await locator.count() > 1)
      throw navigatorFailure(code,'More than one ordinary Navigator control appeared while waiting; no control was clicked');
    throw navigatorFailure('NAVIGATOR_CONTROL_NOT_READY','The unique ordinary Navigator control did not become visible within the remaining budget');
  }
  const count = await locator.count();
  if (count > 1) throw navigatorFailure(code,'More than one ordinary Navigator control matched after waiting; no control was clicked');
  if (count !== 1) throw navigatorFailure('NAVIGATOR_CONTROL_NOT_READY','The ordinary Navigator control disappeared before it was ready to click');
  const websiteGate = hapagWebsiteLoginGuard(locator.page?.());
  if(websiteGate)await websiteGate.assertAvailable();
  await locator.click({timeout:navigatorBudget(end)});
}

async function chooseSearch(page,query,end,lifecycle,observer) {
  const search = page.getByRole('searchbox',{name:'Search text',exact:true});
  await waitNavigatorState(page,end,async()=>await search.isVisible().catch(()=>false));
  if (!officialNavigator(page.url())) throw navigatorFailure('LOGIN_REQUIRED','The fixed Navigator entry did not reach an already logged-in account UI');
  const combo = page.getByRole('combobox',{name:/^(?:Booking No\.|B\/L No\.|Container No\.|Invoice No\.)$/});
  await clickExactlyOne(combo,end);
  await clickExactlyOne(page.getByRole('option',{name:CATEGORY[query.reference_type],exact:true}),end);
  await waitNavigatorState(page,end,async()=>await combo.getAttribute('aria-label')===CATEGORY[query.reference_type],{max:4000,reason:'NAVIGATOR_CATEGORY_NOT_RETAINED'});
  await hapagWebsiteLoginGuard(page)?.assertAvailable();
  await search.fill('',{timeout:navigatorBudget(end)});
  // Clear the old suggestion before starting this task's fresh search. An old
  // result card cannot satisfy a repeated reference after clearing fails.
  await waitNavigatorState(page,end,async()=>{
    const state=await page.evaluate(readNavigatorSearchState);
    return state.candidateCount===0&&state.regions.length===0;
  },{max:4000,reason:'NAVIGATOR_OLD_SUGGESTION_RETAINED'});
  // A response to an older request, even if it arrives now, remains before this
  // index and cannot confirm the present search action.
  const windowStart=observer.markSearchStart();
  await hapagWebsiteLoginGuard(page)?.assertAvailable();
  await search.fill(query.submitted,{timeout:navigatorBudget(end)});
  if (key(await search.inputValue({timeout:navigatorBudget(end)})) !== query.submitted)
    throw navigatorFailure('NAVIGATOR_INPUT_NOT_RETAINED','The account search input does not contain this exact reference');
  lifecycle.searchesStarted++;
  await hapagWebsiteLoginGuard(page)?.assertAvailable();
  await search.press('Enter',{timeout:navigatorBudget(end)});
  return waitNavigatorState(page,end,async()=>{
    if (await combo.getAttribute('aria-label')!==CATEGORY[query.reference_type])
      throw navigatorFailure('NAVIGATOR_CATEGORY_NOT_RETAINED','The visible query type changed while awaiting the account result');
    if (key(await search.inputValue({timeout:navigatorBudget(end)}))!==query.submitted)
      throw navigatorFailure('NAVIGATOR_INPUT_NOT_RETAINED','The visible search reference changed while awaiting the account result');
    const uiResponse=confirmedNavigatorUiResponse(observer.metadata.slice(windowStart),query);
    const result=matchNavigatorSearchState(await page.evaluate(readNavigatorSearchState),query.submitted);
    return result&&uiResponse?{...result,uiResponse}:null;
  },{reason:'NAVIGATOR_FRESH_SEARCH_NOT_CONFIRMED'});
}

export async function selectedContext(page,query,selectedBooking,end,lifecycle) {
  await waitNavigatorState(page,end,async()=>await page.getByRole('tab',{name:'Overview',exact:true}).isVisible().catch(()=>false));
  await clickExactlyOne(page.getByRole('tab',{name:'Overview',exact:true}),end);
  const waitStarted=Date.now(),waitDeadline=Math.min(end,waitStarted+60000);
  const waitAudit={startedAt:new Date(waitStarted).toISOString(),deadline:new Date(waitDeadline).toISOString(),maxMs:60000,
    budgetLimit:end<waitStarted+60000?'REMAINING_TASK_BUDGET':'LOCAL_60_SECONDS',polls:0,elapsedMs:0,status:'WAITING'};
  if(lifecycle)lifecycle.shipmentContextWait=waitAudit;
  try {
  const result=await waitNavigatorState(page,end,async()=>{
    waitAudit.polls++;
    const document=await page.evaluate(readNavigatorDocument),context=document.shipmentContext;
    if(Date.now()>=waitDeadline)return null;
    if (!context?.booking||!context.billOfLading) return null;
    if (key(context.booking)!==key(selectedBooking)||
        query.reference_type==='BOOKING'&&key(context.booking)!==query.submitted||
        query.reference_type==='BILLOFLADING'&&key(context.billOfLading)!==query.submitted)
      throw navigatorFailure('NAVIGATOR_REFERENCE_MISMATCH','The selected visible shipment does not match this typed query and suggestion');
    return document;
  },{max:60000,reason:'NAVIGATOR_SHIPMENT_CONTEXT_NOT_READY'});
  waitAudit.status='READY';return result;
  }catch(error){waitAudit.status='FAILED';waitAudit.errorCode=error.code??'NAVIGATOR_UI_FAILURE';throw error;}
  finally{waitAudit.elapsedMs=Date.now()-waitStarted;}
}

async function openContainer(page,number,end) {
  if (await page.locator('.dialog-card:visible').count())
    throw navigatorFailure('NAVIGATOR_UNEXPECTED_DIALOG','An existing dialog would make the next container selection ambiguous');
  const table=page.locator('[role="tabpanel"]:visible table.q-table').filter({has:page.getByRole('columnheader',{name:'Container No.',exact:true})});
  if(await table.count()!==1)throw navigatorFailure('NAVIGATOR_CONTAINER_TABLE_NOT_READY','The selected shipment container table is missing or ambiguous');
  const cells=table.getByRole('cell').filter({hasText:number.slice(4)});
  const matches=[];
  for(let index=0;index<await cells.count();index++)if(key(await cells.nth(index).innerText())===number)matches.push(index);
  if(matches.length!==1)throw navigatorFailure('NAVIGATOR_CONTAINER_MISMATCH','The container cell does not bind exactly to the requested shipment container');
  await hapagWebsiteLoginGuard(page)?.assertAvailable();
  await cells.nth(matches[0]).click({timeout:navigatorBudget(end)});
  await waitNavigatorState(page,end,async()=>{
    const document=await page.evaluate(readNavigatorDocument);
    return key(document.dialog?.containerNumber)===number&&!document.dialog.transitioning;
  },{reason:'NAVIGATOR_CONTAINER_DIALOG_NOT_READY'});
  return page.locator('.dialog-card:visible');
}

